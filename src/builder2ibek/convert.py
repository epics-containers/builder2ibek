"""
Generic XML to YAML conversion functions
"""

import re
from dataclasses import dataclass
from dataclasses import field as dc_field
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML, CommentedMap

from builder2ibek.builder import Builder, Element
from builder2ibek.fastcs_panda import record_wont_convert, split_pandas, write_fastcs
from builder2ibek.moduleinfos import finalizers, module_infos
from builder2ibek.support_defaults import strip_defaults
from builder2ibek.types import Entity, Generic_IOC
from builder2ibek.vendor_patterns import add_patterns


@dataclass
class ConvertResult:
    """What convert_file wrote, and the warnings for the user"""

    warnings: list[str] = dc_field(default_factory=list)
    # what else was written, e.g. fastcs instances
    notes: list[str] = dc_field(default_factory=list)
    # False for a dedicated PandA IOC, which becomes a fastcs instance instead
    ioc_yaml_written: bool = True
    # fastcs-pandablocks instance folders written, or re-run and left alone
    fastcs_instances: list[Path] = dc_field(default_factory=list)
    # PandA prefixes refused because another instance already serves them
    refused: list[str] = dc_field(default_factory=list)


def convert_file(
    xml: Path, yaml: Path, schema: str, description: str = "", blgui: bool = False
) -> ConvertResult:
    def tidy_up(yaml):
        # add blank lines between major fields
        for field in [
            "ioc_name",
            "description",
            "entities",
            "  - type",
        ]:
            yaml = re.sub(rf"(\n{field})", "\n\\g<1>", yaml)
        return yaml

    """
    Convert a single builder XML file into a single ibek YAML

    An IOC with ADPandABlocks PandAs also gets fastcs-pandablocks instances,
    written next to the ioc.yaml (see builder2ibek.fastcs_panda); a dedicated
    PandA IOC gets only that, and no ioc.yaml.

    The runtime patterns the IOC uses are added to its services-repo instance,
    or only reported when there is none (see builder2ibek.vendor_patterns).

    Returns what was written and the IOC's warnings, one per dropped entity
    type plus any others; the caller reports them to the user.
    """
    builder = Builder()
    builder.load(xml)
    ioc = dispatch(builder, xml, yaml.parent, description=description, blgui=blgui)

    result = ConvertResult()
    split = ioc.panda_split
    if split is not None:
        fastcs = write_fastcs(xml.stem, split, yaml)
        result.fastcs_instances = fastcs.folders
        result.refused = [p.prefix for p in fastcs.refused]
        result.notes = fastcs.notes
        if not split.dedicated:
            record_wont_convert(ioc, split, fastcs.outcome())
        result.warnings = ioc.warnings() + fastcs.warnings
        if split.dedicated or fastcs.ioc_yaml_refused:
            result.ioc_yaml_written = False
            return result
    else:
        result.warnings = ioc.warnings()

    ruamel = YAML()

    ruamel.default_flow_style = False
    # this attribute is for internal use, remove before serialising
    delattr(ioc, "source_file")
    yaml_map = CommentedMap(ioc.model_dump())

    # add support yaml schema
    yaml_map.yaml_add_eol_comment(f"yaml-language-server: $schema={schema}", column=0)

    ruamel.indent(mapping=2, sequence=4, offset=2)

    yaml.parent.mkdir(parents=True, exist_ok=True)
    for name, text in ioc.side_files.items():
        print(f"writing {yaml.parent / name}")
        (yaml.parent / name).write_text(text)
    with yaml.open("w") as stream:
        ruamel.dump(yaml_map, stream, transform=tidy_up)

    try:
        patterns = add_patterns([dict(e) for e in ioc.entities], yaml)
        result.notes += patterns.notes
        result.warnings += patterns.warnings
    except Exception as e:  # noqa: BLE001 -- the ioc.yaml is written; never fail
        result.warnings.append(f"runtime patterns not added: {e}")

    return result


def dispatch(
    builder: Builder,
    filename,
    out_dir: Path | None = None,
    description: str = "",
    blgui: bool = False,
) -> Generic_IOC:
    """
    Dispatch every element in the XML to the correct convertor
    and build a generic IOC from the converted Entities

    out_dir is the folder the converted YAML is written to; convertors that
    generate additional files put them in ioc.side_files, which convert_file
    writes there only when it writes the ioc.yaml.
    """
    if not description:
        description = (
            "auto-generated by https://github.com/epics-containers/builder2ibek"
        )
    ioc = Generic_IOC(
        ioc_name="{{  _global.get_env('IOC_NAME') }}",
        description=description,
        # some default entities for all IOC instances
        entities=[
            {
                "type": "epics.EpicsEnvSet",
                "name": "EPICS_TZ",
                "value": "GMT0BST",
            },
            {
                "type": "epics.EpicsEnvSet",
                "name": "STREAM_PROTOCOL_PATH",
                "value": "/epics/runtime/protocol/",
            },
            {"type": "devIocStats.iocAdminSoft", "IOC": "{{ ioc_name | upper }}"},
        ],
        source_file=filename,
        out_dir=out_dir or Path(),
        blgui=blgui,
    )

    # PandAs become fastcs-pandablocks instances, not ioc.yaml entities
    ioc.panda_split = split_pandas(builder, ioc)

    do_dispatch(builder, ioc)

    # whole-IOC post-processing once every element has been converted
    for finalize in finalizers:
        finalize(ioc)

    return ioc


def do_dispatch(builder: Builder, ioc: Generic_IOC):
    # Generate complete generic list of entities for referencing in plugins.
    ioc.raw_entities = [make_entity(element) for element in builder.elements]

    for element in builder.elements:
        entity = convert_generic(element, ioc)

        do_one_element(element, entity, ioc)

        if entity in ioc.already_converted:
            # we don't want a duplicate, so ignore it
            continue

        ioc.already_converted.append(entity)

    ioc.entities = [Entity(ordered_params(e)) for e in ioc.entities]  # type: ignore
    return ioc


def ordered_params(entity: dict[str, Any]) -> dict[str, Any]:
    """
    An entity's keys in the order the ioc.yaml gives them: type first, then
    the module's param_order, then the rest alphabetically
    """
    param_orders = {
        info.yaml_component: info.param_order for info in module_infos.values()
    }
    order = param_orders.get(str(entity["type"]).split(".")[0], [])
    rest = sorted(
        ((k, v) for k, v in entity.items() if k != "type"),
        key=lambda kv: (
            order.index(kv[0]) if kv[0] in order else len(order),
            kv[0],
        ),
    )
    return {"type": entity["type"], **dict(rest)}


def do_one_element(element: Element, entity: Entity, ioc: Generic_IOC):
    # then dispatch to a specific handler if there is one
    assert isinstance(element, Element)

    if element.module in module_infos:
        info = module_infos[element.module]
    else:
        info = module_infos["generic"]
        info.yaml_component = element.module

    entity.type = f"{info.yaml_component}.{element.name}"
    new_xml = info.handler(entity, element.name, ioc)
    # if the handler added some new entities add them into the IOC
    extras = entity.get_extra_entities()
    if extras:
        for extra_entity in extras:
            ioc.entities.append(extra_entity)
        # move the new entity to after these extras at it is likely to depend on them
        ioc.entities.remove(entity)
        ioc.entities.append(entity)

    # if the handler returns a new XML string, parse it and dispatch the
    # new entities it defines to the correct handler
    if new_xml:
        new_builder = Builder()
        new_builder.load_string(new_xml)
        ioc.entities.remove(entity)
        do_dispatch(new_builder, ioc)
    if entity.is_deleted():
        ioc.entities.remove(entity)
    else:
        add_defaults(entity, info.defaults)

    # remove fields that have None value
    for key in list(entity.keys()):
        if entity[key] is None:
            del entity[key]

    strip_defaults(entity)


def add_defaults(entity: dict[str, Any], defaults: dict[str, dict[str, Any]]):
    this_entity_defaults = defaults.get(entity["type"])
    if this_entity_defaults:
        needed_defaults = {
            k: v for k, v in this_entity_defaults.items() if k not in entity
        }
        entity.update(needed_defaults)


def _has_leading_zero(val: str) -> bool:
    """Return True when a numeric string has meaningful leading zeros."""
    return len(val) > 1 and val[0] == "0" and val[1] != "."


_CROSS_REF_RE = re.compile(r"^\$\(([^)]+)\)$")


def _jinja_type_filter(raw_value: str | None) -> str:
    """Return the Jinja2 type filter for a raw XML attribute value."""
    try:
        f = float(raw_value)  # type: ignore
        if _has_leading_zero(raw_value):  # type: ignore
            return "string"
        return "int" if f.is_integer() else "float"
    except (ValueError, TypeError):
        return "string"


def make_entity(element: Element) -> Entity:
    """
    default Entity creation is a direct mapping
    of element name and attribute names/values to
    Entity type and argument names/values
    """

    entity = Entity()
    entity.type = f"{element.module}.{element.name}"
    entity.set_xml_attributes(element.attributes)

    for attribute_name, attribute_val in element.attributes.items():
        # detect cross-references like $(MRES) and convert to Jinja2 templates
        m = _CROSS_REF_RE.match(attribute_val)
        if m:
            ref_name = m.group(1)
            ref_val = element.attributes.get(ref_name)
            type_filter = _jinja_type_filter(ref_val)
            entity[attribute_name] = f"{{{{ {ref_name} | {type_filter} }}}}"
            continue

        # convert to numeric type if appropriate, otherwise Serialize will
        # put quotes around numbers in the YAML
        try:
            f = float(attribute_val)
            # Preserve leading zeros (e.g. "010", "00020") as strings —
            # they encode meaningful formatting (PV name segments, etc.)
            if _has_leading_zero(attribute_val):
                entity[attribute_name] = attribute_val
            elif f.is_integer():
                entity[attribute_name] = int(f)
            else:
                entity[attribute_name] = f
        except ValueError:
            entity[attribute_name] = attribute_val

    return entity


def convert_generic(element: Element, ioc: Generic_IOC) -> Entity:
    entity = make_entity(element)
    ioc.entities.append(entity)
    return entity
